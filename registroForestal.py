#opciones
opciones = widgets.Dropdown(
    options=[
        ("Agregar",1),("Eliminar",2),("Imprimir",3),("Descargar",4)],
    description="Opción",
    layout=layoutTercio,
    style=styleLabel)

tipoDescarga = widgets.Dropdown(
    options=[
        ("Por lotes","lotes"),
        ("Por especies","especies"),("Todo","todo")],
    description="Descargar",
    layout=layoutTercio,
    style=styleLabel)

#Botones
boton = widgets.Button(
    description="Ejecutar",
    button_style="success",
    icon="check")

btnLimpiar = widgets.Button(
    description="Limpiar",
    button_style="warning",
    icon="trash")

salida = widgets.Output()

def ejecutar(b):
    global contadorEspecies
    with salida:
        clear_output()
        opcion = opciones.value

        #Agregar
        if opcion == 1:
            camposVacios = (
                not nombreBrigada.value.strip() or
                not responsableBrigada.value.strip() or
                not idLote.value.strip() or
                not municipio.value.strip() or
                not departamento.value.strip() or
                not nombreComun.value.strip() or
                cantidadIndividuos.value <= 0
            )
            if camposVacios:
                print("Faltan datos por ingresar.")
                return
            nombreClave = nombreComun.value.strip().lower()

            if nombreClave in idsEspecies:
                idRegistro = idsEspecies[nombreClave]
            else:
                prefijo = "PAJ" if tipoEspecie.value == "Pájaro" else "FLO"
                idRegistro = f"{prefijo}-{contadorEspecies:04d}"
                idsEspecies[nombreClave] = idRegistro
                contadorEspecies += 1

            registroForestal.append([
                idRegistro,
                tipoEspecie.value,
                nombreComun.value.strip(),
                tipoRegistro.value,
                cantidadIndividuos.value,
                departamento.value.strip(),
                municipio.value.strip(),
                nombreBrigada.value.strip(),
                idLote.value.strip(),
            ])
            print(f"Registro {idRegistro} agregado — total: {len(registroForestal)}")

          #Eliminar
        elif opcion == 2:
            try:
                indiceEliminar = int(nombreComun.value.strip()) - 1
                if 0 <= indiceEliminar < len(registroForestal):
                    registroForestal.pop(indiceEliminar)
                    print(f"Registro {indiceEliminar + 1} eliminado")
                else:
                    print("Número no válido")

            except:
                print("Ingresa el número del registro en Nombre común")

                #Imprimir
        elif opcion == 3:
            if registroForestal:
                for datos in registroForestal:
                    print(f"\nID: {datos[0]}")
                    print(f"Especie: {datos[1]}")
                    print(f"Nombre común: {datos[2]}")
                    print(f"Tipo: {datos[3]}")
                    print(f"Cantidad: {datos[4]}")
                    print(f"Municipio: {datos[5]}")
                    print(f"Brigada: {datos[6]}")
                    print(f"Lote: {datos[7]}")
            else:
                print("No hay registros guardados")

        #Descargar
        elif opcion == 4:
            if tipoDescarga.value == "lotes":
                lotesRegistrados = []
                for datos in registroForestal:
                    if datos[6] not in lotesRegistrados:
                        lotesRegistrados.append(datos[6])
                        with open(f"lote_{datos[6]}.csv","w",newline="") as archivo:
                            writer = csv.writer(archivo)
                            writer.writerow([
                                "ID",
                                "Especie",
                                "Nombre común",
                                "Tipo",
                                "Cantidad",
                                "Municipio",
                                "Brigada",
                                "Lote"])
                            for fila in registroForestal:
                                if fila[8] == datos[8]:
                                    writer.writerow(fila)
                        files.download(f"lote_{datos[8]}.csv")

        elif opcion == 4:
            if not registroForestal:
                print("Sin registros para exportar.")
                return

            cabecera = ["ID","Especie","Nombre común","Tipo","Cantidad",
                        "Departamento","Municipio","Brigada","Lote"]

            def escribir_y_descargar(nombre_archivo, filas):
                with open(nombre_archivo, "w", newline="", encoding="utf-8-sig") as f:
                    writer = csv.writer(f)
                    writer.writerow(cabecera)
                    writer.writerows(filas)
                files.download(nombre_archivo)
                print(f"Descargado: {nombre_archivo} ({len(filas)} registros)")

            modo = tipoDescarga.value

            if modo == "lotes":
                lotes = sorted({d[8] for d in registroForestal})
                for lote in lotes:
                    filas = [d for d in registroForestal if d[8] == lote]
                    escribir_y_descargar(f"lote_{lote}.csv", filas)

            elif modo == "especies":
                especies = sorted({d[1] for d in registroForestal})
                for esp in especies:
                    filas = [d for d in registroForestal if d[1] == esp]
                    escribir_y_descargar(f"{esp.lower()}.csv", filas)

            elif modo == "todo":
                escribir_y_descargar("inventario_forestal_completo.csv", registroForestal)


def limpiar(b):
    with salida:
        clear_output()

    nombreBrigada.value = ""
    responsableBrigada.value = ""
    colaboradorUno.value     = ""
    colaboradorDos.value     = ""
    colaboradorTres.value    = ""
    idLote.value = ""
    cantidadIndividuos.value= 0
    municipio.value = ""
    nombreComun.value = ""
    departamento.value = ""
    tipoEspecie.value = "Pájaro"
    tipoRegistro.value = "Migratoria"


