import csv
from google.colab import files
import ipywidgets as widgets
from IPython.display import display, clear_output

if "registroForestal" not in dir():
    raise RuntimeError("Ejecuta primero la Celda 1 para inicializar el estado.")

layoutMitad = widgets.Layout(width="48%", margin="6px 1%")
layoutCompleto = widgets.Layout(width="98%", margin="6px 1%")
layoutTercio = widgets.Layout(width="31%", margin="6px 1%")

styleLabel = {"description_width": "initial"}

#Brigadas
tituloBrigada = widgets.HTML(
    "<h3 style='color:GREY;'>INFORMACIÓN DE LA BRIGADA</h3>")

nombreBrigada = widgets.Text(
    description="Nombre de brigada",
    placeholder="Ej: Brigada Amazonas 01",
    layout=layoutMitad,
    style=styleLabel)

responsableBrigada = widgets.Text(
    description="Lider",
    placeholder="Nombre del lider de brigada",
    layout=layoutMitad,
    style=styleLabel)

colaboradorUno = widgets.Text(
    description="Colaborador 1",
    layout=layoutMitad,
    style=styleLabel)

colaboradorDos = widgets.Text(
    description="Colaborador 2",
    layout=layoutMitad,
    style=styleLabel)

colaboradorTres = widgets.Text(
    description="Colaborador 3",
    layout=layoutMitad,
    style=styleLabel)

#Lugares
tituloLote = widgets.HTML(
    "<h3 style='color:GREY;'>LOTE DE MUESTREO</h3>")

idLote = widgets.Text(
    description="ID lote",
    placeholder="Ej: LOTE001",
    layout=layoutTercio,
    style=styleLabel)

